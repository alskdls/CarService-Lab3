
CREATE TABLE clients (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         name VARCHAR(255) NOT NULL,
                         phone VARCHAR(255) NOT NULL
);

CREATE TABLE cars (
                      vin VARCHAR(17) PRIMARY KEY,
                      brand VARCHAR(255) NOT NULL,
                      model VARCHAR(255) NOT NULL,
                      year INTEGER NOT NULL,
                      client_id BIGINT NOT NULL,
                      CONSTRAINT fk_cars_client
                          FOREIGN KEY (client_id) REFERENCES clients(id)
);

CREATE TABLE mechanics (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           name VARCHAR(255) NOT NULL,
                           specialization VARCHAR(255),
                           busy BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE repair_orders (
                               id VARCHAR(255) PRIMARY KEY,
                               car_vin VARCHAR(17) NOT NULL,
                               mechanic_id BIGINT,
                               status VARCHAR(50) NOT NULL,
                               CONSTRAINT fk_orders_car
                                   FOREIGN KEY (car_vin) REFERENCES cars(vin),
                               CONSTRAINT fk_orders_mechanic
                                   FOREIGN KEY (mechanic_id) REFERENCES mechanics(id)
);

CREATE TABLE jobs (
                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      description VARCHAR(255) NOT NULL,
                      parts_cost NUMERIC(12, 2) NOT NULL,
                      labor_cost NUMERIC(12, 2) NOT NULL,
                      completed BOOLEAN NOT NULL DEFAULT FALSE,
                      order_id VARCHAR(255) NOT NULL,
                      CONSTRAINT fk_jobs_order
                          FOREIGN KEY (order_id) REFERENCES repair_orders(id)
);

CREATE INDEX idx_cars_client_id ON cars(client_id);
CREATE INDEX idx_orders_car_vin ON repair_orders(car_vin);
CREATE INDEX idx_orders_mechanic_id ON repair_orders(mechanic_id);
CREATE INDEX idx_jobs_order_id ON jobs(order_id);
